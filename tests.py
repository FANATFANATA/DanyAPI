def main() -> int:
    for stream in (sys.stdout, sys.stderr):
        reconfigure = getattr(stream, "reconfigure", None)
        if reconfigure is not None:
            try:
                reconfigure(errors="replace")
            except (ValueError, OSError):
                pass
    jobs, pytest_args = parse_args(sys.argv[1:])
    steps = build_steps(pytest_args)
    use_color = sys.stdout.isatty()
    run_started = time.monotonic()
    results: list[StepResult] = []
    if jobs == 1:
        for name, runner in steps:
            result = run_step(name, runner)
            results.append(result)
            print_step(result, use_color)
    else:
        lock = threading.Lock()
        collected: dict[int, StepResult] = {}
        with ThreadPoolExecutor(max_workers=jobs) as pool:
            futures = {pool.submit(run_step, name, runner): index for index, (name, runner) in enumerate(steps)}
            for future in as_completed(futures):
                result = future.result()
                collected[futures[future]] = result
                print_step(result, use_color, lock)
        results = [collected[index] for index in range(len(steps))]
    wall_time = time.monotonic() - run_started
    print()
    print("======== SUMMARY ========")
    width = max(len(name) for name, *_rest in results)
    failed = 0
    skipped = 0
    for name, status, _elapsed, _output, _detail in results:
        if status == STATUS_PASS:
            mark = status_paint(STATUS_PASS.ljust(4), use_color)
        elif status == STATUS_SKIP:
            skipped += 1
            mark = status_paint(STATUS_SKIP.ljust(4), use_color)
        else:
            failed += 1
            mark = status_paint(STATUS_FAIL.ljust(4), use_color)
        print(f"{mark}  {name.ljust(width)}")
    print()
    if skipped:
        print(f"{skipped} step(s) were skipped because the tool is not installed, see the SKIP lines above.")
    if failed:
        print(f"RESULT: FAILED ({failed} check(s) failed)")
        print(f"total time: {wall_time:.1f}s wall clock across {jobs} job(s)")
        return 1
    print("RESULT: ALL CHECKS PASSED")
    print(f"total time: {wall_time:.1f}s wall clock across {jobs} job(s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
